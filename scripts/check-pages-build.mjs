#!/usr/bin/env node
/** Confirm that the actual production artifact can serve the play URL. */
import { strict as assert } from "node:assert";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const dist = process.argv[2] ?? "dist";
const expectedBase = process.argv[3] ?? "/BrowserGame/";
const read = relative => {
  const full = join(dist, relative);
  assert.ok(existsSync(full), "Missing deploy file: "+relative);
  return readFileSync(full, "utf8");
};
assert.ok(expectedBase.startsWith("/") && expectedBase.endsWith("/"));
const home = read("index.html");
const play = read("tests/terrain-preview.html");
assert.match(home,/BASTIONFALL|Bastionfall/);
assert.match(play,/canvas id="terrain"/);
assert.ok(home.includes(expectedBase+"assets/"), "Landing bundle must use hosted base");
assert.ok(!home.includes('src="/src/main.ts"'), "Raw dev entry must not reach production");
assert.ok(!play.includes('from "/src/'), "Raw TS imports must not reach production");
assert.ok(!play.includes('import("/src/'), "Raw TS dynamic imports must be bundled");
for (const f of ["assets/lantern-cc0.glb",
  "assets/characters/warden-kaykit.glb",
  "assets/characters/scrapper-kaykit.glb",
  "assets/characters/runner-kaykit.glb"]) {
  const path=join(dist,f);
  assert.ok(existsSync(path) && statSync(path).size>100_000,
    "Published game lost required bundled authored 3D asset "+f);
}
// VQ.02: the compiled game must include the exact six locally bundled
// artist-authored CC0 castle GLBs. Hosting cannot silently omit the new art.
for(const [file,minBytes] of [
  ["kenney-keep-main.glb",50000],
  ["kenney-turret-body.glb",30000],
  ["kenney-turret-roof.glb",25000],
  ["kenney-pad-border.glb",10000],
  ["kenney-pad-inlay.glb",12000],
  ["kenney-pad-glyph.glb",25000],
]){
  const relative="assets/environment/"+file;
  const absolute=join(dist,relative);
  assert.ok(existsSync(absolute)&&statSync(absolute).size>=minBytes,
    "Published Warden scene lost VQ.02 authored CC0 GLB "+relative);
}
// VQ.02b: compiled private-site game must actually ship the seven locally
// bundled source-pinned 3D nature assets (not just mention filenames).
for(const [file,bytes] of [
  ["kenney-pine-layered.glb",28804],
  ["kenney-pine-rounded.glb",14488],
  ["kenney-canopy-oak.glb",14644],
  ["kenney-canopy-plateau.glb",16304],
  ["kenney-canopy-detailed.glb",31412],
  ["kenney-rocks-mossy.glb",23764],
  ["kenney-rocks-lichen.glb",7552],
]){
  const path=join(dist,"assets/scenery",file);
  assert.ok(existsSync(path)&&statSync(path).size===bytes,
    "Published game missing unchanged authored Kenney nature GLB "+file);
}
const bundles = readdirSync(join(dist,"assets")).filter(f=>f.endsWith(".js"));
assert.ok(bundles.length>0, "Missing production JS bundles");
const scripts = bundles.map(f=>readFileSync(join(dist,"assets",f),"utf8")).join("\n");
for (const asset of ["assets/lantern-cc0.glb","assets/characters/warden-kaykit.glb",
    "assets/characters/scrapper-kaykit.glb","assets/characters/runner-kaykit.glb"]) {
  assert.ok(scripts.includes(expectedBase+asset),
    "Bundled Three model URL ignores base path: "+asset);
}
assert.ok(scripts.includes(expectedBase+"assets/environment/"),
  "Compiled VQ.02 castle GLB URLs ignore Vite hosted-base prefix");
assert.ok(scripts.includes(expectedBase+"assets/scenery/"),
  "Compiled VQ.02b nature GLB URLs ignore Vite hosted-base prefix");

// The playable button is HTML generated by a bundled runtime JS module,
// so it does not appear in the static index.html entry itself.
assert.ok(scripts.includes("tests/terrain-preview.html"),
  "The compiled landing page has lost its game launch route");
console.log("PASS: deploy output serves the actual playable page, all 17 GLBs, built JS, correct "+expectedBase+" prefix");
